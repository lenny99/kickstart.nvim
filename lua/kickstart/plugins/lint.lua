-- Linting

vim.pack.add { 'https://github.com/mfussenegger/nvim-lint' }

local lint = require 'lint'
lint.linters_by_ft = {
  -- rumdl is a standalone Rust binary, installed via `brew install rumdl`.
  -- Unlike markdownlint it does not require Node/npm.
  markdown = { 'rumdl' },
}

-- nvim-lint's bundled rumdl definition reads the JSON report from stderr,
-- but rumdl (>= 0.3) writes it to stdout. Without this, Markdown diagnostics
-- never show up.
lint.linters.rumdl.stream = 'stdout'

