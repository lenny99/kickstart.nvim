-- Only run linters whose executable is actually installed. Without this,
-- nvim-lint tries to spawn missing tools and aborts with an error such as
-- "Error running markdownlint: ENOENT" when opening a Markdown file.
local function linter_installed(linter)
  local cmd = linter.cmd
  if type(cmd) == 'function' then cmd = cmd() end
  return type(cmd) == 'string' and vim.fn.executable(cmd) == 1
end

-- Create autocommand which carries out the actual linting
-- on the specified events.
local lint_augroup = vim.api.nvim_create_augroup('lint', { clear = true })
vim.api.nvim_create_autocmd({ 'BufEnter', 'BufWritePost', 'InsertLeave' }, {
  group = lint_augroup,
  callback = function()
    -- Only run the linter in buffers that you can modify in order to
    -- avoid superfluous noise, notably within the handy LSP pop-ups that
    -- describe the hovered symbol using Markdown.
    if vim.bo.modifiable then lint.try_lint(nil, { filter = linter_installed }) end
  end,
})
